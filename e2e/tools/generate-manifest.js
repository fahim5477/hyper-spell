#!/usr/bin/env node
// generate-manifest.js — `npm run e2e:update`.
//
// Freezes the game's surface into e2e/manifest.json by booting the real bundle
// in a real browser and reading the game's own tables.
//
// This is the answer to a game that changes every day. Specs 06, 07 and 10
// iterate this file, so new spells, maps and bosses are covered without anyone
// editing a test; spec 14 fails when the live game and this file disagree, so
// the working day looks like:
//
//     change the game  ->  suite goes red on 14  ->  npm run e2e:update
//                      ->  read the diff  ->  commit it
//
// The diff is the point. It is a reviewable changelog of what today's work did
// to the game's surface.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';
import { startServer } from '../support/server.js';
import { liveSurface, sourceSurface, manifestPath, REPO } from './surface.js';

const argv = process.argv.slice(2);
const skipBuild = argv.includes('--no-build');

async function main() {
  if (!skipBuild) {
    process.stdout.write('building bundles… ');
    for (const script of ['build', 'build:guide']) {
      execFileSync('npm', ['run', script], { cwd: REPO, stdio: 'pipe' });
    }
    console.log('done');
  }

  const server = await startServer();
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    const failures = [];
    page.on('pageerror', e => failures.push(e.message));
    page.on('console', m => { if (m.type() === 'error') failures.push(m.text()); });

    await page.goto(`${server.url}/index.html?nomenu`);
    await page.waitForFunction(() => !!globalThis.HS, null, { timeout: 15_000 });

    // A manifest generated from a broken page would bake the breakage in as the
    // expected surface, and every spec that iterates it would then agree with
    // the bug. Refuse rather than record.
    if (failures.length) {
      throw new Error(`the game logged errors while booting; refusing to record a manifest from it:\n  ${failures.join('\n  ')}`);
    }

    const live = await liveSurface(page);
    const source = sourceSurface();

    const manifest = {
      // Deliberately no timestamp: this file is diffed on every change, and a
      // regenerated-but-identical surface must produce an empty diff.
      note: 'Generated by `npm run e2e:update`. Do not edit by hand — regenerate and review the diff.',
      counts: {
        spells: Object.keys(live.spells).length,
        maps: live.maps.length,
        bosses: live.bosses.length,
        secretBosses: live.secretBosses.length,
      },
      ...live,
      source,
    };

    writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
    console.log(`wrote e2e/manifest.json — ${manifest.counts.spells} spells, ${manifest.counts.maps} maps, ` +
      `${manifest.counts.bosses} bosses, ${manifest.counts.secretBosses} secret, ` +
      `${source.keyCodes.length} keybindings, ${source.gameStates.length} game states.`);
  } finally {
    await browser.close();
    await server.stop();
  }
}

main().catch(err => { console.error(err.message); process.exit(1); });
